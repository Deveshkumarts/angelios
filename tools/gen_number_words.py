"""
Generates app/src/main/java/org/sih/itantra/speech/NumberWords.kt: cardinal number words 0-99 for the
Indian languages, used by TtsTextNormalizer so the voices say "पच्चीस" instead of "दो पाँच".

Source: indic-num2words 1.3.2 (Apache-2.0) https://github.com/sutariyaraj/indic-num2words
Only 0-99 is taken: those are whole words in each language. Its hundreds/thousands are glued from
parts ("நான்கு நூறு" instead of "நானூறு"), so bigger numbers stay digit-by-digit in the app.

  pip install indic-num2words==1.3.2
  python tools/gen_number_words.py
"""
import os
import sys
import unicodedata

from num_to_words import num_to_word

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "app", "src", "main", "java",
                   "org", "sih", "itantra", "speech", "NumberWords.kt")
LANGS = {"HINDI": "hi", "MARATHI": "mr", "BENGALI": "bn", "GUJARATI": "gu", "PUNJABI": "pa", "ODIA": "or",
         "TAMIL": "ta", "TELUGU": "te", "KANNADA": "kn", "MALAYALAM": "ml"}


# Standard Hindi spellings 0-99. The library's Hindi list has non-standard forms (अड़्तिस, सैतालिस,
# तिर्सठ, निन्यान्बे); a TTS -> STT check showed the recogniser writes these standard ones.
HINDI_STANDARD = (
    "शून्य एक दो तीन चार पाँच छह सात आठ नौ दस ग्यारह बारह तेरह चौदह पंद्रह सोलह सत्रह अठारह उन्नीस "
    "बीस इक्कीस बाईस तेईस चौबीस पच्चीस छब्बीस सत्ताईस अट्ठाईस उनतीस तीस इकतीस बत्तीस तैंतीस चौंतीस "
    "पैंतीस छत्तीस सैंतीस अड़तीस उनतालीस चालीस इकतालीस बयालीस तैंतालीस चवालीस पैंतालीस छियालीस सैंतालीस "
    "अड़तालीस उनचास पचास इक्यावन बावन तिरेपन चौवन पचपन छप्पन सत्तावन अट्ठावन उनसठ साठ इकसठ बासठ तिरेसठ "
    "चौंसठ पैंसठ छियासठ सड़सठ अड़सठ उनहत्तर सत्तर इकहत्तर बहत्तर तिहत्तर चौहत्तर पचहत्तर छिहत्तर सतहत्तर "
    "अठहत्तर उन्यासी अस्सी इक्यासी बयासी तिरासी चौरासी पचासी छियासी सत्तासी अट्ठासी नवासी नब्बे इक्यानबे "
    "बानबे तिरानबे चौरानबे पंचानबे छियानबे सत्तानबे अट्ठानबे निन्यानबे"
).split()
assert len(HINDI_STANDARD) == 100


def clean(w: str) -> str:
    # The source has a few stray zero-width/space characters; MMS voices don't know them
    w = unicodedata.normalize("NFC", w)  # e.g. Telugu U+0C46 U+0C56 -> U+0C48, as the voices expect
    return " ".join(w.replace("‌", "").replace("‍", "").split())


def main():
    lines = [
        "package org.sih.itantra.speech",
        "",
        "import org.sih.itantra.domain.model.Language",
        "",
        "/**",
        " * Cardinal number words 0..99 per Indian language. GENERATED by tools/gen_number_words.py from",
        " * indic-num2words 1.3.2 (Apache-2.0, github.com/sutariyaraj/indic-num2words); Hindi uses the standard",
        " * spellings listed in that script. Do not edit by hand.",
        " */",
        "object NumberWords {",
        "    val UNDER_100: Map<Language, List<String>> = mapOf(",
    ]
    for enum_name, code in LANGS.items():
        words = HINDI_STANDARD if code == "hi" else [clean(num_to_word(n, code)) for n in range(100)]
        joined = ", ".join('"' + w.replace('"', '\\"') + '"' for w in words)
        lines.append(f"        Language.{enum_name} to listOf({joined}),")
    lines[-1] = lines[-1].rstrip(",")
    lines += ["    )", "}", ""]
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print("wrote", OUT)


if __name__ == "__main__":
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8")
    main()
